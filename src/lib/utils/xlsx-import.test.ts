import { describe, it, expect } from 'vitest';
import { buildXlsxBytes } from './xlsx-export';
import { parseXlsxBuffer, parseXlsxToTsv, colLetterToIndex } from './xlsx-import';

describe('xlsx-import utility', () => {
  it('converts column letter to zero-based index correctly', () => {
    expect(colLetterToIndex('A')).toBe(0);
    expect(colLetterToIndex('B')).toBe(1);
    expect(colLetterToIndex('Z')).toBe(25);
    expect(colLetterToIndex('AA')).toBe(26);
    expect(colLetterToIndex('AB')).toBe(27);
  });

  it('parses valid .xlsx bytes generated by buildXlsxBytes', async () => {
    const originalHeaders = ['กลุ่ม', 'เลขเฉพาะกลุ่ม', 'รหัสนิสิต', 'ชื่อ-นามสกุล'];
    const originalRows = [
      ['1', 'T101', '6701501011', 'พระมหาสมชาย กิตฺติโสภโณ'],
      ['2', 'T201', '6701501022', 'Ven. Dhammapalo'],
    ];

    const bytes = buildXlsxBytes([
      {
        name: 'นิสิตกลุ่ม',
        headers: originalHeaders,
        rows: originalRows,
      },
    ]);

    const parsedRows = await parseXlsxBuffer(bytes);
    expect(parsedRows.length).toBeGreaterThanOrEqual(3); // Headers + 2 rows

    // Check headers
    expect(parsedRows[0]).toEqual(originalHeaders);
    // Check first data row
    expect(parsedRows[1]).toEqual(originalRows[0]);
    // Check second data row
    expect(parsedRows[2]).toEqual(originalRows[1]);

    // Test TSV conversion
    const tsv = await parseXlsxToTsv(bytes);
    expect(tsv).toContain('พระมหาสมชาย กิตฺติโสภโณ');
    expect(tsv).toContain('Ven. Dhammapalo');
    expect(tsv).toContain('T101');
  });
});
